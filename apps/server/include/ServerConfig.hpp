#ifndef SERVERCONFIG_HPP
#define SERVERCONFIG_HPP

#include <cstdint>
#include <exception>
#include <span>
#include <stdexcept>
#include <string>
#include <string_view>

#include "engine/core/Logger.hpp"

namespace rtype::server {

constexpr int EPITECH_EXIT_FAIL = 84;

/**
 * @brief An invalid command line. what() names the option at fault.
 */
class ConfigError : public std::runtime_error {
public:
    using std::runtime_error::runtime_error;
};

/**
 * @brief `-h` or `--help` was given, wherever it appears: print
 * ServerConfig::usage() and exit with 0.
 */
class HelpRequested : public std::exception {};

struct ServerConfig {
    std::uint16_t port = 4242;
    std::uint32_t seed = 0;
    engine::core::log::Level logLevel = engine::core::log::Level::EG_INFO;

    /**
     * @brief Reads the options of `server.md` § Command line.
     *
     * The last occurrence of a repeated option wins. Ports and seeds are
     * whole decimal numbers only: no sign, no trailing character.
     * @param args The arguments without the program name.
     * @throw HelpRequested on `-h` or `--help`.
     * @throw ConfigError on an unknown option, a missing value, no
     * `--seed`, a port outside 1-65535, a seed outside 0-4294967295 or an
     * unknown log level.
     */
    [[nodiscard]] static ServerConfig parse(
        std::span<const std::string_view> args);

    /**
     * @brief The help generated by CLI11: the synopsis and every option
     * with its description and default.
     */
    [[nodiscard]] static std::string usage(std::string_view program);
};

}

#endif
